const assert = require('node:assert/strict');
const path = require('node:path');
const root = process.argv[2] ?? path.resolve(__dirname, '..');
const { harness } = require(path.join(root, 'scripts/check-ticket-statuses.cjs'));
const plain = value => JSON.parse(JSON.stringify(value));
async function run() {
  const h = harness();
  const { store, access, load } = h;
  const scoring = load('lib/ticket-scoring');
  const patents = load('lib/ranking-patents');
  for (const [points,name] of [[0,"Soldado raso"],[99,"Soldado raso"],[100,"Soldado"],[249,"Soldado"],[250,"Cabo"],[499,"Cabo"],[500,"Sargento"],[799,"Sargento"],[800,"Subtenente"],[1199,"Subtenente"],[1200,"Tenente"],[1799,"Tenente"],[1800,"Capitão"],[2599,"Capitão"],[2600,"Major"],[3599,"Major"],[3600,"Coronel"],[4999,"Coronel"],[5000,"General"],[10000,"General"]]) assert.equal(patents.patentProgress(points).patent.name,name);
  assert.equal(patents.rankingPatents.length,10);
  assert.equal(patents.patentProgress(99).remaining,1);
  assert.equal(patents.patentProgress(100).progress,0);
  assert.equal(patents.patentProgress(175).progress,50);
  assert.equal(patents.patentProgress(250).next.name,'Sargento');
  assert.equal(patents.patentProgress(5000).next,null);
  assert.equal(patents.patentProgress(5000).progress,100);
  assert.equal(patents.patentProgress(4999).remaining,1);
  const ranking = load('services/mock-ranking');
  const catalog = () => load('data/technicians').readTechnicians().technicians;
  const view = (month = 'todos', filter = '') => ranking.getRankingView(store.getTicketsSnapshot().tickets, catalog(), month, filter);
  const key = store.ticketsStorageKey;
  assert.deepEqual(plain(scoring.priorityPoints), { Baixa: 10, Normal: 20, Alta: 40 });
  assert.equal(scoring.scoreMonth('2026-11-01T02:00:00Z'), '2026-10');
  assert.equal(scoring.scoreMonth('2026-11-01T03:00:00Z'), '2026-11');
  assert.throws(() => view());
  assert.ok(access.loginDemo('usuario@demo.sjp','Usuario123!')); assert.throws(() => view());
  assert.ok(access.loginDemo('tecnico@demo.sjp','Tecnico123!'));
  const before = view();
  assert.ok(before.contributions.every(t => t.score.technicianId === 'tecnico-demo'));
  assert.throws(() => view('todos','tecnico-redes-demo'));
  assert.throws(() => view('bad'));
  for (const ticket of store.getTicketsSnapshot().tickets.filter(t => t.technicianId === 'tecnico-demo' && t.executionState === 'Em andamento')) await store.actOnMockTicket(ticket.id,{action:'pausar',pauseCategory:'Intervalo',text:'Preparação da demonstração do ranking'});
  const input = priority => ({ title: 'Entrega para ranking ' + priority, description: 'Descrição do atendimento fictício para testar pontos', requesterId: 'usuario-demo', unitId: 'saude-hospital', callType: 'Suporte de TI', nature: 'Hardware', modality: 'Presencial', contact: '0000', impact:'Teste', urgency:'Teste', material:'', pickupLocation:'', priority, equipment:null });
  const ids = [];
  for (const priority of ['Baixa','Normal','Alta']) {
    assert.ok(access.loginDemo('admin@demo.sjp','Admin123!'));
    const created = store.createMockTicket(input(priority)); ids.push(created.id);
    assert.equal(created.score, undefined);
    assert.ok(access.loginDemo('tecnico@demo.sjp','Tecnico123!'));
    const claimed = await store.actOnMockTicket(created.id,{action:'assumir'}); assert.equal(claimed.score,undefined);
    const started = await store.actOnMockTicket(created.id,{action:'iniciar'}); assert.equal(started.score,undefined);
    const completed = await store.actOnMockTicket(created.id,{action:'concluir',text:'Entrega fictícia realizada corretamente'});
    assert.equal(completed.score.points, scoring.priorityPoints[priority]); assert.equal(completed.score.state,'provisorio');
    assert.equal(completed.status,'Em análise'); assert.equal(completed.score.technicianId,'tecnico-demo');
    const prior = plain(view());
    await assert.rejects(() => store.actOnMockTicket(created.id,{action:'concluir',text:'Repetição que não deve gerar crédito'}));
    assert.deepEqual(plain(view()), prior);
  }
  const totals = view();
  assert.equal(totals.provisional, before.provisional + 70);
  assert.equal(totals.confirmed, before.confirmed);
  assert.ok(access.loginDemo('usuario@demo.sjp','Usuario123!'));
  for (const id of ids.slice(0,2)) await store.validateMockTicket(id,{action:'confirmar',rating:5});
  const rejected = await store.validateMockTicket(ids[2],{action:'pendencia',text:'Ainda é necessária revisão do serviço'});
  assert.equal(rejected.score.state,'em_revisao'); assert.equal(rejected.score.points,40);
  assert.ok(access.loginDemo('tecnico@demo.sjp','Tecnico123!'));
  assert.equal(view().confirmed,before.confirmed+30);
  assert.equal(view().own.lifetimeConfirmed,before.confirmed+30);
  assert.equal(view().provisional,before.provisional);
  assert.equal(view().review,before.review+40);
  assert.ok(access.loginDemo('admin@demo.sjp','Admin123!'));
  const completeAdmin = view(); assert.ok(completeAdmin.contributions.some(t=>t.score.technicianId !== 'tecnico-demo'));
  const filtered = view('todos','tecnico-demo'); assert.equal(filtered.rows.length,1);
  assert.equal(filtered.rows[0].position,completeAdmin.rows.find(r=>r.id==='tecnico-demo').position);
  assert.ok(filtered.contributions.every(t=>t.score.technicianId==='tecnico-demo'));
  await store.validateMockTicket(ids[2],{action:'devolver',text:'Rever o serviço antes de nova conclusão'});
  // Outra pessoa pode assumir após transferência; crédito antigo permanece em revisão.
  const source = store.getTicketsSnapshot().tickets.find(t=>t.id===ids[2]);
  const names = catalog();
  const transferable = scoring.withLegacyScore({...source,technicianId:'tecnico-redes-demo',technician:'Pedro Almeida'});
  assert.equal(transferable.score.technicianId,'tecnico-demo');
  const updatedDelivery = scoring.concludeScore(transferable,{id:'tecnico-redes-demo',name:'Pedro Almeida'},new Date().toISOString());
  assert.equal(updatedDelivery.score.technicianId,'tecnico-redes-demo'); assert.equal(updatedDelivery.score.points,40);
  assert.ok(updatedDelivery.score.revisions.some(r=>r.technicianId==='tecnico-demo'));
  assert.ok(names.length > 1);
  assert.ok(access.loginDemo('tecnico@demo.sjp','Tecnico123!'));
  await store.actOnMockTicket(ids[2],{action:'iniciar'});
  const reconcluded = await store.actOnMockTicket(ids[2],{action:'concluir',text:'Serviço revisado e entregue novamente'});
  assert.equal(reconcluded.score.state,'provisorio'); assert.equal(view().provisional,before.provisional+40);
  assert.equal(view().review,before.review);
  assert.ok(reconcluded.score.revisions.length>=3);
  assert.ok(access.loginDemo('usuario@demo.sjp','Usuario123!'));
  const confirmed = await store.validateMockTicket(ids[2],{action:'confirmar',rating:4});
  assert.equal(confirmed.score.state,'confirmado'); assert.equal(confirmed.status,'Resolvido');
  await assert.rejects(() => store.validateMockTicket(ids[2],{action:'confirmar',rating:5}));
  assert.ok(access.loginDemo('tecnico@demo.sjp','Tecnico123!'));
  assert.equal(view().confirmed,before.confirmed+70); assert.equal(view().provisional,before.provisional);
  const final = view();
  const reloaded = harness(h.data.get(key));
  assert.equal(reloaded.store.getTicketsSnapshot().error,null);
  assert.deepEqual(plain(reloaded.store.getTicketsSnapshot().tickets),plain(store.getTicketsSnapshot().tickets));
  const month = scoring.scoreMonth(confirmed.score.completedAt);
  const monthly = view(month);
  assert.ok(monthly.contributions.some(t=>t.id===confirmed.id));
  assert.ok(view('1999-01').contributions.length===0);
  assert.equal(view('1999-01').own.lifetimeConfirmed, view().own.lifetimeConfirmed);
  assert.deepEqual(plain(view('1999-01').own.classification),plain(view().own.classification));
  assert.equal(view().own.lifetimeConfirmed,before.confirmed + 70);
  assert.equal(view().own.classification.patent.name,patents.patentProgress(before.confirmed + 70).patent.name);
  assert.equal(view().confirmed,final.confirmed);
  assert.ok(store.getTicketsSnapshot().tickets.every(t=>!t.score || scoring.validTicketScore(t.score)));
  // Empate recebe a mesma posição; provisório não altera ordem por confirmado.
  const seed = store.getTicketsSnapshot().tickets.find(t=>t.id===ids[0]);
  const competitors = [{...seed, id:80001,score:{...seed.score,technicianId:'tecnico-demo',points:10}}, {...seed,id:80002,score:{...seed.score,technicianId:'tecnico-redes-demo',points:10}}];
  const tied = ranking.getRankingView(competitors,catalog(),'todos');
  assert.equal(tied.rows.find(r=>r.id==='tecnico-demo').position,tied.rows.find(r=>r.id==='tecnico-redes-demo').position);
  // Falha de gravação: conclusão não publica score/estado parcial.
  assert.ok(access.loginDemo('admin@demo.sjp','Admin123!'));
  const fail = store.createMockTicket(input('Alta'));
  assert.ok(access.loginDemo('tecnico@demo.sjp','Tecnico123!'));
  await store.actOnMockTicket(fail.id,{action:'assumir'}); await store.actOnMockTicket(fail.id,{action:'iniciar'});
  const snapshot = plain(store.getTicketsSnapshot()), write = h.window.localStorage.setItem;
  h.window.localStorage.setItem=()=>{throw Error('full')};
  await assert.rejects(() => store.actOnMockTicket(fail.id,{action:'concluir',text:'Conclusão não salva por falta de espaço'}));
  assert.deepEqual(plain(store.getTicketsSnapshot()),snapshot);
  h.window.localStorage.setItem=write;
  const broken = plain(store.getTicketsSnapshot().tickets); broken[0].score={...confirmed.score,points:-10};
  assert.ok(harness(JSON.stringify(broken)).store.getTicketsSnapshot().error);
  console.log('PASS: faixas e limites de patentes, progressão acumulada independente do mês, exclusão de pontos provisórios/em revisão; pesos, períodos/fuso, acesso por papel, privacidade do detalhamento, provisório/confirmado/revisão, reconclusão sem duplicação, autoria/transferência, recarga, filtros/empates e falha de armazenamento.');
}
run().catch(error=>{console.error(error);process.exitCode=1});
